import { access, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  FeatureParityMatrix,
  ParityDimensions
} from '../src/parity/FeatureMatrix.js'
import {
  CompilerSupportMatrix,
  ExperimentalPackageSupport,
  PlatformSupportMatrix
} from '../src/support/SupportMatrix.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'book', 'support-matrix.md')
const checkOnly = process.argv.includes('--check')
const output = await renderSupportMatrix()

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')

  if (current !== output) {
    throw new Error(
      'book/support-matrix.md is stale; run npm run docs:support'
    )
  }

  console.log('generated support matrix is current')
} else {
  await writeFile(outputPath, output)
  console.log('generated book/support-matrix.md')
}

async function renderSupportMatrix() {
  const packages = await readPackages()
  const features = FeatureParityMatrix.filter(entry => entry.kind === 'feature')
  const diagnostics = FeatureParityMatrix.filter(entry => {
    return entry.kind === 'diagnostic'
  })
  const lines = [
    '# Feature And Support Matrix',
    '',
    '<!-- Generated by scripts/generate-support-matrix.mjs. Do not edit by hand. -->',
    '',
    'This is the source-of-truth support page for the README and book. “Supported”',
    'describes the primary JavaScript compiler unless a row explicitly names the',
    'Lumen-written bootstrap compiler.',
    '',
    'Regenerate it with `npm run docs:support`.',
    '',
    '## Compiler Architecture',
    '',
    '| Area | Status | Actual behavior |',
    '| --- | --- | --- |',
    ...CompilerSupportMatrix.map(row => {
      return `| ${row.area} | ${status(row.status)} | ${row.detail} |`
    }),
    '',
    '## JavaScript/Bootstrap Parity Features',
    '',
    `Each row is exercised across ${ParityDimensions.join(', ')}.`,
    '',
    '| Feature | Status | Fixture |',
    '| --- | --- | --- |',
    ...features.map(entry => {
      return `| ${entry.name} | Parity-tested subset | \`${entry.fixture}\` |`
    }),
    '',
    '## JavaScript/Bootstrap Diagnostic Parity',
    '',
    '| Diagnostic | Status | Fixture |',
    '| --- | --- | --- |',
    ...diagnostics.map(entry => {
      return `| ${entry.name} | Parity-tested subset | \`${entry.fixture}\` |`
    }),
    '',
    'Rows absent from the two parity tables are not claimed as bootstrap-compiler',
    'support. The primary JavaScript compiler supports more language and runtime',
    'features than the bootstrap subset.',
    '',
    '## Platform Support',
    '',
    '| Platform | Status | Actual behavior |',
    '| --- | --- | --- |',
    ...PlatformSupportMatrix.map(row => {
      return `| ${row.area} | ${status(row.status)} | ${row.detail} |`
    }),
    '',
    '## Bundled Package Support',
    '',
    `The repository contains ${packages.length} bundled package manifests.`,
    '“Available” means source and exports exist; it is not a stability guarantee.',
    '',
    '| Package | Status | Actual behavior |',
    '| --- | --- | --- |',
    ...packages.map(pkg => {
      const experimental = ExperimentalPackageSupport[pkg.name]
      const packageStatus = experimental?.status ?? 'available'
      const detail = experimental?.detail ??
        `${pkg.exports.length} exported helper${pkg.exports.length === 1 ? '' : 's'}; see its package README and manifest.`
      return `| \`${pkg.name}\` | ${status(packageStatus)} | ${detail} |`
    }),
    ''
  ]

  return `${lines.join('\n')}\n`
}

async function readPackages() {
  const packagesRoot = join(root, 'packages')
  const entries = await readdir(packagesRoot, { withFileTypes: true })
  const packages = []

  for (const entry of entries) {
    if (!entry.isDirectory()) continue

    const manifestPath = join(packagesRoot, entry.name, 'photon.json')

    try {
      await access(manifestPath)
    } catch {
      continue
    }

    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
    packages.push({
      name: manifest.name,
      exports: manifest.exports ?? []
    })
  }

  return packages.sort((left, right) => left.name.localeCompare(right.name))
}

function status(value) {
  return value
    .split(' ')
    .map(word => `${word[0].toUpperCase()}${word.slice(1)}`)
    .join(' ')
}
